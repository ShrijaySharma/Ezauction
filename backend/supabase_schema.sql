-- ============================================================
-- EzAuction Supabase Master Schema (Multi-Auction Ready)
-- ============================================================

-- 1. Create Auctions Table (Tenant Root)
CREATE TABLE IF NOT EXISTS public.auctions (
  id            text primary key,                    -- slug e.g. "ipl2025"
  name          text not null,                       -- display name
  admin_username text unique not null,
  admin_password text not null,                      -- bcrypt hash
  status        text default 'active',               -- active | archived
  created_at    timestamptz default now()
);

-- 2. Create Users Table
CREATE TABLE IF NOT EXISTS public.users (
  id bigint generated by default as identity primary key,
  auction_id text references public.auctions(id) on delete cascade,
  username text not null,
  password text not null,
  role text not null check (role in ('admin', 'host', 'app_owner', 'owner', 'super_admin')),
  team_id bigint,
  created_at timestamptz default now()
);

-- 3. Create Teams Table
CREATE TABLE IF NOT EXISTS public.teams (
  id bigint generated by default as identity primary key,
  auction_id text not null references public.auctions(id) on delete cascade,
  name text not null,
  owner_id bigint,
  owner_name text,
  logo text,
  budget numeric default 1000000,
  bidding_locked integer default 0,
  access_code text,
  plain_password text,
  created_at timestamptz default now()
);

-- 4. Create Players Table
CREATE TABLE IF NOT EXISTS public.players (
  id bigint generated by default as identity primary key,
  auction_id text not null references public.auctions(id) on delete cascade,
  name text not null,
  image text,
  thumb_url text,
  role text not null,
  country text,
  base_price numeric not null,
  status text default 'AVAILABLE', -- 'AVAILABLE', 'SOLD', 'UNSOLD'
  sold_price numeric,
  sold_to_team bigint,
  was_unsold integer default 0,
  serial_number integer,
  age integer,
  created_at timestamptz default now()
);

-- 5. Create Bids Table
CREATE TABLE IF NOT EXISTS public.bids (
  id bigint generated by default as identity primary key,
  auction_id text not null references public.auctions(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete cascade,
  team_id bigint not null references public.teams(id) on delete cascade,
  amount numeric not null,
  timestamp timestamptz default now()
);

-- 6. Create Auction State Table
CREATE SEQUENCE IF NOT EXISTS public.auction_state_id_seq;

CREATE TABLE IF NOT EXISTS public.auction_state (
  id bigint primary key default nextval('public.auction_state_id_seq'),
  auction_id text not null references public.auctions(id) on delete cascade,
  status text default 'STOPPED',
  current_player_id bigint,
  bidding_locked integer default 0,
  bid_increment_1 numeric default 500,
  bid_increment_2 numeric default 1000,
  bid_increment_3 numeric default 5000,
  max_players_per_team integer default 10,
  enforce_max_bid integer default 0,
  sequential_mode integer default 0,           -- 0 = random, 1 = sequential by serial_number
  sequential_last_serial integer default NULL, -- last served serial_number (for wrap-around)
  updated_at timestamptz default now()
);

-- 7. Create Trades Table (Audit log for player trades between teams)
CREATE TABLE IF NOT EXISTS public.trades (
  id bigint generated by default as identity primary key,
  auction_id text not null references public.auctions(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete cascade,
  player_name text not null,
  from_team_id bigint not null references public.teams(id) on delete cascade,
  from_team_name text not null,
  to_team_id bigint not null references public.teams(id) on delete cascade,
  to_team_name text not null,
  amount numeric not null,
  traded_at timestamptz default now()
);

-- 8. Unique Constraints & Indexes
CREATE UNIQUE INDEX IF NOT EXISTS uq_teams_auction_name ON public.teams (auction_id, name);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_auction_username ON public.users (auction_id, username) WHERE auction_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_super_admin_username ON public.users (username) WHERE role = 'super_admin';
CREATE UNIQUE INDEX IF NOT EXISTS uq_astate_auction ON public.auction_state(auction_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_players_auction_id ON public.players (auction_id, id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_teams_auction_id ON public.teams (auction_id, id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_auction_id ON public.users (auction_id, id);

-- 9. Performance Indexes
CREATE INDEX IF NOT EXISTS idx_players_auction ON public.players(auction_id);
CREATE INDEX IF NOT EXISTS idx_teams_auction ON public.teams(auction_id);
CREATE INDEX IF NOT EXISTS idx_bids_auction ON public.bids(auction_id);
CREATE INDEX IF NOT EXISTS idx_trades_auction ON public.trades(auction_id);
CREATE INDEX IF NOT EXISTS idx_users_auction ON public.users(auction_id);
CREATE INDEX IF NOT EXISTS idx_astate_auction ON public.auction_state(auction_id);

-- 10. Foreign Keys (Separate constraints to avoid cyclic dependencies)
ALTER TABLE public.users DROP CONSTRAINT IF EXISTS fk_user_team;
ALTER TABLE public.users ADD CONSTRAINT fk_user_team FOREIGN KEY (team_id) REFERENCES public.teams(id);

ALTER TABLE public.teams DROP CONSTRAINT IF EXISTS fk_team_owner;
ALTER TABLE public.teams ADD CONSTRAINT fk_team_owner FOREIGN KEY (owner_id) REFERENCES public.users(id);

ALTER TABLE public.players DROP CONSTRAINT IF EXISTS fk_player_sold_team;
ALTER TABLE public.players ADD CONSTRAINT fk_player_sold_team FOREIGN KEY (sold_to_team) REFERENCES public.teams(id);

-- 11. Durable Server-Side Sessions Table
CREATE TABLE IF NOT EXISTS public.app_sessions (
  sid text primary key,
  data jsonb not null,
  expires_at timestamptz not null
);
CREATE INDEX IF NOT EXISTS idx_app_sessions_expires_at ON public.app_sessions (expires_at);
ALTER TABLE public.app_sessions ENABLE ROW LEVEL SECURITY;

